#!/usr/bin/env node
// Generates difftest/testdata/writer-shards/shard-<n>.json: the whole-case
// partition of TestWriterReplay used by the non-Ubuntu CI shards.
//
//   shard = SHA256(UTF-8(caseID))[0] mod 4
//
// Inputs are only the template files (writers.json, then sorted
// writers.d/*.json) and the golden files; no Go source is consulted.
//
// Usage:
//   node gen-writer-shards.mjs            write the committed manifests
//   node gen-writer-shards.mjs --check    verify the committed manifests; writes nothing
//   node gen-writer-shards.mjs --out DIR  write fresh manifests into a new/empty DIR (recapture)
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const data = join(here, "..", "testdata");
const committed = join(data, "writer-shards");
const SHARDS = 4;
const RECORDER = "recorder-fake-docker";

// The design's exact table (spec 3.2); generation fails on any drift.
const EXPECTED = [
  { cases: 291, golden: 341, windowsPass: 101, windowsSkip: 190, windowsCompared: 115 },
  { cases: 284, golden: 335, windowsPass: 105, windowsSkip: 179, windowsCompared: 113 },
  { cases: 260, golden: 319, windowsPass: 101, windowsSkip: 159, windowsCompared: 114 },
  { cases: 262, golden: 323, windowsPass: 100, windowsSkip: 162, windowsCompared: 109 },
];

const shardFor = (id) => createHash("sha256").update(id, "utf8").digest()[0] % SHARDS;

function templateFiles() {
  const names = existsSync(join(data, "writers.d"))
    ? readdirSync(join(data, "writers.d")).filter((n) => n.endsWith(".json")).sort((a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b)))
    : [];
  return ["writers.json", ...names.map((n) => `writers.d/${n}`)];
}

function goldenCounts() {
  const files = ["writers.jsonl"];
  const dir = join(data, "golden", "writers.d");
  if (existsSync(dir)) for (const n of readdirSync(dir).sort()) if (n.endsWith(".jsonl")) files.push(`writers.d/${n}`);
  const counts = new Map();
  for (const f of files) {
    for (const line of readFileSync(join(data, "golden", f), "utf8").split("\n")) {
      if (line === "") continue;
      const id = JSON.parse(line).case;
      counts.set(id, (counts.get(id) ?? 0) + 1);
    }
  }
  return counts;
}

function build() {
  const seen = new Set();
  const shards = Array.from({ length: SHARDS }, (_, shard) => ({
    shard, ordinary: [], posix: [], golden: 0, windowsPass: 0, windowsSkip: 0, windowsCompared: 0,
  }));
  const goldens = goldenCounts();
  const cases = new Set();
  for (const f of templateFiles()) {
    for (const tpl of JSON.parse(readFileSync(join(data, f), "utf8"))) {
      if (seen.has(tpl.id)) throw new Error(`duplicate case id ${tpl.id}`);
      seen.add(tpl.id);
      cases.add(tpl.id);
      const s = shards[shardFor(tpl.id)];
      const n = goldens.get(tpl.id) ?? 0;
      s.golden += n;
      if (tpl.posixOnly) {
        s.posix.push(tpl.id);
        s.windowsSkip++;
      } else {
        s.ordinary.push(tpl.id);
        s.windowsPass++;
        s.windowsCompared += n;
      }
    }
  }
  for (const id of goldens.keys()) if (!cases.has(id)) throw new Error(`golden ${id} has no template`);
  if (seen.has(RECORDER)) throw new Error(`${RECORDER} collides with a template id`);
  shards[0].posix.push(RECORDER); // exactly once, shard 0 only
  for (const s of shards) {
    s.ordinary.sort();
    s.posix.sort();
    const e = EXPECTED[s.shard];
    const got = { cases: s.ordinary.length + s.posix.length - (s.shard === 0 ? 1 : 0), golden: s.golden, windowsPass: s.windowsPass, windowsSkip: s.windowsSkip, windowsCompared: s.windowsCompared };
    for (const k of Object.keys(e)) if (got[k] !== e[k]) throw new Error(`shard ${s.shard} ${k}: got ${got[k]}, want ${e[k]}`);
  }
  return shards.map((s) => [`shard-${s.shard}.json`, JSON.stringify(s, null, 2) + "\n"]);
}

const args = process.argv.slice(2);
const files = build();
if (args[0] === "--check" && args.length === 1) {
  let bad = 0;
  for (const [name, text] of files) {
    const p = join(committed, name);
    if (!existsSync(p) || readFileSync(p, "utf8") !== text) {
      console.error(`writer-shards: ${name} missing or differs from regenerated bytes`);
      bad++;
    }
  }
  const extra = existsSync(committed) ? readdirSync(committed).filter((n) => !files.some(([f]) => f === n)) : [];
  for (const n of extra) { console.error(`writer-shards: unexpected file ${n}`); bad++; }
  if (bad) process.exit(1);
  console.log(`writer-shards: ${files.length} manifests match`);
} else if (args.length === 0 || (args[0] === "--out" && args.length === 2)) {
  const dir = args[0] === "--out" ? args[1] : committed;
  if (args[0] === "--out" && existsSync(dir) && readdirSync(dir).length > 0) throw new Error(`${dir} is not empty`);
  mkdirSync(dir, { recursive: true });
  for (const [name, text] of files) writeFileSync(join(dir, name), text);
  console.log(`writer-shards: wrote ${files.length} manifests to ${dir}`);
} else {
  console.error("usage: gen-writer-shards.mjs [--check | --out DIR]");
  process.exit(2);
}
