#!/usr/bin/env node
/**
 * Capture fallback terminal footage for the video (Bucket 1 #2).
 *
 * Records stdout/stderr of the teleprompter's machine-safe commands from a pin
 * checkout into an asciinema-compatible v2 cast (no GUI required), plus a
 * plain .log twin. Does not invent Docker/API results — those stay human.
 *
 * Usage:
 *   node scripts/capture-fallback-footage.mjs
 *   FAULTLINE_REHEARSE_TAG=v0.1.10-buildweek node scripts/capture-fallback-footage.mjs
 *
 * Output: docs/fallback-footage/
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync, mkdtempSync, rmSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..");
const PIN = process.env.FAULTLINE_REHEARSE_TAG ?? "v0.1.10-buildweek";
const OUT = join(REPO, "docs", "fallback-footage");
const SAMPLE_ROOT =
  "sha256:f85c446dfd5ab92222b10a314e79209a8a7dc10ee69af9d2deaa04aceafeb7d9";

mkdirSync(OUT, { recursive: true });

function run(cwd, command, args) {
  const started = Date.now() / 1000;
  const result = spawnSync(command, args, {
    cwd,
    encoding: "utf8",
    env: { ...process.env, FAULTLINE_NO_BROWSER: "1" },
    maxBuffer: 16 * 1024 * 1024
  });
  const ended = Date.now() / 1000;
  return {
    started,
    ended,
    status: result.status ?? 1,
    stdout: result.stdout ?? "",
    stderr: result.stderr ?? ""
  };
}

function toCast(header, events) {
  return `${JSON.stringify(header)}\n${events.map((e) => JSON.stringify(e)).join("\n")}\n`;
}

const work = mkdtempSync(join(tmpdir(), "faultline-footage-"));
const clone = join(work, "faultline");
const steps = [];

try {
  let r = run(work, "git", ["clone", "--no-local", REPO, clone]);
  steps.push(["git clone", r]);
  r = run(clone, "git", ["fetch", "--tags", "--force", "origin"]);
  steps.push(["git fetch --tags", r]);
  r = run(clone, "git", ["checkout", "--detach", PIN]);
  steps.push([`git checkout ${PIN}`, r]);
  r = run(clone, "pnpm", ["install", "--frozen-lockfile"]);
  steps.push(["pnpm install --frozen-lockfile", r]);

  const commands = [
    ["pnpm fl doctor", ["pnpm", "fl", "doctor"]],
    ["pnpm fl judge-proof --export-only", ["pnpm", "fl", "judge-proof", "--export-only"]],
    [
      `pnpm fl verify docs/samples/self-incident-commit-proof --expect-root ${SAMPLE_ROOT}`,
      ["pnpm", "fl", "verify", "docs/samples/self-incident-commit-proof", "--expect-root", SAMPLE_ROOT]
    ]
  ];

  // Optional Docker-backed beats
  const dockerOk =
    spawnSync("docker", ["info"], { encoding: "utf8" }).status === 0;
  if (dockerOk) {
    commands.push([
      "pnpm fl demo live-git --export-only",
      ["pnpm", "fl", "demo", "live-git", "--export-only"]
    ]);
  }

  for (const [label, argv] of commands) {
    const result = run(clone, argv[0], argv.slice(1));
    steps.push([label, result]);
    if (result.status !== 0) {
      console.error(`Command failed: ${label} (exit ${result.status})`);
      console.error(result.stderr.slice(-2000));
      process.exit(1);
    }
  }

  const t0 = steps[0][1].started;
  const events = [];
  let log = `# FaultLine fallback footage — pin ${PIN}\n# Generated by scripts/capture-fallback-footage.mjs\n\n`;

  for (const [label, result] of steps) {
    const offset = Math.max(0, result.started - t0);
    const output = `$ ${label}\n${result.stdout}${result.stderr}`;
    events.push([offset, "o", output.replace(/\r/g, "")]);
    log += `$ ${label}\n${result.stdout}${result.stderr}\n[exit ${result.status}]\n\n`;
  }

  const header = {
    version: 2,
    width: 120,
    height: 40,
    timestamp: Math.floor(Date.now() / 1000),
    env: { TERM: "xterm-256color", SHELL: "/bin/bash" },
    title: `FaultLine fallback footage (${PIN})`
  };

  writeFileSync(join(OUT, "judge-path.cast"), toCast(header, events));
  writeFileSync(join(OUT, "judge-path.log"), log);
  writeFileSync(
    join(OUT, "README.md"),
    `# Fallback footage (machine-captured)

Pin: \`${PIN}\`  
Generator: \`node scripts/capture-fallback-footage.mjs\`

| Asset | Purpose |
| --- | --- |
| \`judge-path.cast\` | asciinema v2 cast of clone → pin → doctor → judge-proof → verify → live-git export |
| \`judge-path.log\` | Plain-text twin for editors who do not use asciinema |

**Not captured here (human / env-gated):** \`fl witness propose --live\`, \`fl demo full\` (Docker), live Codex \`/feedback\`.

Replay: \`asciinema play docs/fallback-footage/judge-path.cast\`  
Render (optional, local): \`agg docs/fallback-footage/judge-path.cast docs/fallback-footage/judge-path.gif\`

Honesty: this is the same command sequence as [video-teleprompter.md](../video-teleprompter.md) machine-safe beats — not a substitute for the narrated Devpost video.
`
  );
  console.log(`Wrote ${join(OUT, "judge-path.cast")} and judge-path.log`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
