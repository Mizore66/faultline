#!/usr/bin/env node
/**
 * Devpost gallery screenshot automation (Bucket 1 #3).
 *
 * Installs Playwright into a temp directory (no root lockfile mutation) and
 * screenshots docs/self-incident-proof-preview.html via file:// (no server).
 *
 * Usage: node scripts/capture-devpost-gallery.mjs
 * Output: docs/devpost-gallery/*.png
 */
import { spawnSync } from "node:child_process";
import {
  mkdirSync,
  existsSync,
  writeFileSync,
  mkdtempSync,
  rmSync,
  readdirSync
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..");
const OUT = join(REPO, "docs", "devpost-gallery");
const PREVIEW = join(REPO, "docs", "self-incident-proof-preview.html");

mkdirSync(OUT, { recursive: true });

async function main() {
  if (!existsSync(PREVIEW)) {
    console.error(`Missing ${PREVIEW}`);
    process.exit(1);
  }

  const playDir = mkdtempSync(join(tmpdir(), "faultline-playwright-"));
  try {
    writeFileSync(join(playDir, "package.json"), JSON.stringify({ private: true }, null, 2));
    let r = spawnSync("npm", ["install", "playwright@1.54.1", "--no-save", "--no-package-lock"], {
      cwd: playDir,
      encoding: "utf8",
      stdio: "inherit"
    });
    if (r.status !== 0) process.exit(1);
    r = spawnSync("npx", ["playwright", "install", "chromium"], {
      cwd: playDir,
      encoding: "utf8",
      stdio: "inherit"
    });
    if (r.status !== 0) process.exit(1);

    const fileUrl = pathToFileURL(PREVIEW).href;
    const runner = `
      const { chromium } = require('playwright');
      (async () => {
        const browser = await chromium.launch({ headless: true });
        const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
        await page.goto(${JSON.stringify(fileUrl)}, { waitUntil: 'load', timeout: 60000 });
        await page.waitForTimeout(1000);
        await page.screenshot({ path: ${JSON.stringify(join(OUT, "01-proof-preview-full.png"))}, fullPage: true });
        const markers = [
          ['02-timeline', /timeline|PASS|FAIL|turn/i],
          ['03-verify', /MATCH|verify|VALID|root/i],
          ['04-prevention', /prevention|PREVENTION|AGENTS/i]
        ];
        for (const [name, re] of markers) {
          try {
            const loc = page.getByText(re).first();
            if (await loc.count()) {
              await loc.scrollIntoViewIfNeeded();
              await page.screenshot({ path: ${JSON.stringify(OUT)} + '/' + name + '.png' });
            }
          } catch {}
        }
        await browser.close();
      })().catch((e) => { console.error(e); process.exit(1); });
    `;
    const runnerPath = join(playDir, "capture.cjs");
    writeFileSync(runnerPath, runner);
    r = spawnSync("node", [runnerPath], {
      cwd: playDir,
      encoding: "utf8",
      stdio: "inherit",
      env: process.env
    });
    if (r.status !== 0) process.exit(1);

    writeFileSync(
      join(OUT, "README.md"),
      `# Devpost gallery screenshots

Generated by \`node scripts/capture-devpost-gallery.mjs\` from \`docs/self-incident-proof-preview.html\` (Playwright in a temp install — root lockfile untouched).

| File | Intent |
| --- | --- |
| \`01-proof-preview-full.png\` | Full proof-page snapshot (judge zero-install path) |
| \`02-*.png\` … | Best-effort section crops when text markers exist |

Re-run before paste. Do not invent UI states the preview does not show.
`
    );
    const shots = readdirSync(OUT).filter((n) => n.endsWith(".png"));
    console.log(`Wrote ${shots.length} PNG(s) under ${OUT}: ${shots.join(", ")}`);
  } finally {
    rmSync(playDir, { recursive: true, force: true });
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
