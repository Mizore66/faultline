// Generates internal/turnsnap/fold_table.go from the running Node's V8:
//   node internal/turnsnap/gen/gen.mjs | gofmt > internal/turnsnap/fold_table.go
// Node 22.22.2 produced the committed file. With --verify it first checks,
// for every BMP code unit c (about two minutes), that /c/i (no u flag)
// matches exactly the units with the same canonical form.
//
// The table is ECMAScript Canonicalize (22.2.2.7.3) without the u flag:
// toUpperCase of the unit; the unit itself when that is not one unit, or
// when it would map a non-ASCII unit to ASCII.
const canon = (c) => {
  const u = String.fromCharCode(c).toUpperCase();
  if (u.length !== 1) return c;
  const cu = u.charCodeAt(0);
  if (c >= 128 && cu < 128) return c;
  return cu;
};
const units = [];
for (let c = 0; c < 0x10000; c++) if (c < 0xd800 || c > 0xdfff) units.push(c);
if (process.argv.includes("--verify")) {
  const hay = units.map((c) => String.fromCharCode(c)).join("");
  const esc = (s) => s.replace(/[.*+?^${}()|[\]\\\/]/g, "\\$&");
  for (const c of units) {
    const got = [...hay.matchAll(new RegExp(esc(String.fromCharCode(c)), "gi"))].map((m) => hay.charCodeAt(m.index));
    const want = units.filter((x) => canon(x) === canon(c));
    if (got.join() !== want.join()) throw new Error(`fold class of U+${c.toString(16)} differs`);
  }
}
const hex = (c) => `0x${c.toString(16).toUpperCase().padStart(4, "0")}`;
let go = `// Code generated by gen/gen.mjs from Node ${process.versions.node} (V8 ${process.versions.v8}, ICU ${process.versions.icu}, Unicode ${process.versions.unicode}); DO NOT EDIT.

package turnsnap

// canonicalUnit holds every BMP code unit whose canonical form under a JS
// regular expression's i flag (without u) differs from itself.
var canonicalUnit = map[uint16]uint16{
`;
for (const c of units) if (canon(c) !== c) go += `\t${hex(c)}: ${hex(canon(c))},\n`;
go += "}\n";
process.stdout.write(go);
