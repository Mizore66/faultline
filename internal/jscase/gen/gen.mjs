// Generates internal/jscase/tables.go from the running Node's ICU:
//   node internal/jscase/gen/gen.mjs > internal/jscase/tables.go
// Node 22.22.2 (ICU 78.2, Unicode 17) produced the committed file.
const lower = [];
const cased = [];
const ignorable = [];
const reCased = /^\p{Cased}$/u;
const reIgnorable = /^\p{Case_Ignorable}$/u;
for (let c = 0; c <= 0x10ffff; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  const s = String.fromCodePoint(c);
  // Alone, Σ has no cased letter before it, so this is the non-final form.
  const l = s.toLocaleLowerCase("en-US");
  if (l !== s) lower.push([c, [...l].map((x) => x.codePointAt(0))]);
  if (reCased.test(s)) cased.push(c);
  if (reIgnorable.test(s)) ignorable.push(c);
}
const ranges = (list) => {
  const out = [];
  for (const c of list) {
    const last = out.at(-1);
    if (last && last[1] === c - 1) last[1] = c;
    else out.push([c, c]);
  }
  return out;
};
const hex = (c) => `0x${c.toString(16).toUpperCase()}`;
let go = `// Code generated by gen/gen.mjs from Node ${process.versions.node} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}); DO NOT EDIT.

package jscase

// lowerMap holds every code point whose full lowercase mapping (root locale,
// outside a final-sigma context) differs from itself.
var lowerMap = map[rune][]rune{
`;
for (const [c, l] of lower) go += `\t${hex(c)}: {${l.map(hex).join(", ")}},\n`;
go += `}

// casedRanges and ignorableRanges are the Cased and Case_Ignorable
// properties, as sorted inclusive ranges.
var casedRanges = [][2]rune{
`;
for (const [a, b] of ranges(cased)) go += `\t{${hex(a)}, ${hex(b)}},\n`;
go += `}

var ignorableRanges = [][2]rune{
`;
for (const [a, b] of ranges(ignorable)) go += `\t{${hex(a)}, ${hex(b)}},\n`;
go += "}\n";
process.stdout.write(go);
